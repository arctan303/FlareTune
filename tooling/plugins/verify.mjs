import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, writeFile, realpath } from 'node:fs/promises';
import { resolve, relative, isAbsolute } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { compiledPluginManifests } from '../../shared/plugins/catalog.js';
import { canonicalPluginManifest, HOST_PLUGIN_API_VERSION } from '../../shared/plugins/manifest.js';
import { createPluginHostBuild, collectPluginHostSources } from './host-identity.mjs';
import { assertNoDevSourceOverride } from './dev-source.mjs';

const root = fileURLToPath(new URL('../../', import.meta.url));
const digest = data => createHash('sha256').update(data).digest('hex');
export async function createPluginLock() {
  const inventory = JSON.parse(await readFile(resolve(root, 'tooling/plugins/sources.json'), 'utf8'));
  let delivery = { plugins: {} };
  try { delivery = JSON.parse(await readFile(resolve(root, 'tooling/plugins/delivery-source.generated.json'), 'utf8')); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  assert.ok(Object.keys(delivery.plugins || {}).every(id => !Object.hasOwn(inventory.plugins, id)), 'Remote plugins cannot replace workspace source definitions');
  const packages = { ...inventory.plugins, ...delivery.plugins };
  const host = await createPluginHostBuild(root);
  const hostSources = await collectPluginHostSources(root);
  assert.deepEqual(Object.keys(packages).sort(), compiledPluginManifests.map(item => item.id).sort(), 'Every compiled plugin needs a source inventory');
  const plugins = [];
  for (const manifest of compiledPluginManifests) {
    const sources = [];
    const definition = packages[manifest.id];
    assert.ok(definition.source && Array.isArray(definition.files) && definition.files.length, 'Plugin source is required');
    for (const path of [...new Set([...hostSources.map(item => item.path), ...definition.files])].sort()) {
      const absolute = await realpath(resolve(root, path));
      const resolved = relative(root, absolute);
      assert.ok(!resolved.startsWith('..') && !isAbsolute(resolved), 'Plugin source must stay in workspace');
      sources.push({ path, sha256: digest(await readFile(absolute)) });
    }
    plugins.push({ id: manifest.id, version: manifest.version, hostApiVersion: manifest.hostApiVersion,
      apiVersion: manifest.apiVersion, source: definition.source,
      manifestDigest: digest(canonicalPluginManifest(manifest)), sourceDigest: digest(JSON.stringify(sources)), sources });
  }
  return { schemaVersion: 1, hostApiVersion: HOST_PLUGIN_API_VERSION, host, plugins };
}
export async function verifyPluginLock({ update = false } = {}) {
  await assertNoDevSourceOverride(root);
  const lock = await createPluginLock();
  const lockPath = resolve(root, 'plugins.lock.json');
  const metadata = lock.plugins.map(({ sources, source, ...entry }) => entry);
  const generated = `// Generated by npm run plugins:lock; verify before every combined build.\nexport const pluginHostBuild = Object.freeze(${JSON.stringify(lock.host, null, 2)});\nexport const pluginBuilds = Object.freeze(${JSON.stringify(metadata, null, 2)});\n`;
  if (update) {
    await writeFile(lockPath, `${JSON.stringify(lock, null, 2)}\n`);
    await writeFile(resolve(root, 'shared/plugins/build.generated.js'), generated);
  } else {
    assert.deepEqual(JSON.parse(await readFile(lockPath, 'utf8')), lock,
      'Plugin sources changed: review them, then run npm run plugins:lock');
    assert.equal(await readFile(resolve(root, 'shared/plugins/build.generated.js'), 'utf8'), generated,
      'Plugin frontend/backend build metadata differs from the lock');
  }
  return metadata;
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const metadata = await verifyPluginLock({ update: process.argv.includes('--update') });
  console.log(JSON.stringify({ plugins: metadata }, null, 2));
}
